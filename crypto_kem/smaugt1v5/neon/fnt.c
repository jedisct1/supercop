void fnt_mv(int16x8_t acc[SMAUGT_K][SMAUGT_N_VEC], int16x8_t s[SMAUGT_K][SMAUGT_N_VEC], int16x8_t s_asymmetric[SMAUGT_K][SMAUGT_N_VEC>>1],  int16x8_t A[SMAUGT_K][SMAUGT_K][SMAUGT_N_VEC]){
    for (size_t j = 0; j < SMAUGT_K; j++){
        fnt(&(s[j][0]));
        fnt_point_mul_extended_opt(&(s_asymmetric[j][0]), &(s[j][0]), fnt_pre_asymmetric_table_extended, fnt_asymmetric_const);
    }
    
    for (size_t i = 0; i < SMAUGT_K; i++) {
        for (size_t j = 0; j < SMAUGT_K; j++) {
            fnt(&(A[i][j][0]));
        }
    }
    
    for (size_t j = 0; j < SMAUGT_K; j++){
        //fnt_mv_base_mul_mont(&(acc[j][0]), &(A[j][0][0]), &(s[0][0]), &(s_asymmetric[0][0]), fnt_asymmetric_const);
        fnt_asymmetric_mul(&(acc[j][0]), &(A[j][0][0]), &(s[0][0]), &(s_asymmetric[0][0]), fnt_asymmetric_const);
    }

    
    for (size_t j = 0; j < SMAUGT_K; j++){ 
        invfnt(&(acc[j][0]));
    }
}


