void fnt_base_mul_montgomery(int16x8_t *polyout, int16x8_t *poly1, int16x8_t *poly2) {
    int16x8_t poly2_asymmetric[SMAUGT_N_VEC>>1] = {0};
    
    fnt_point_mul_extended(poly2_asymmetric, poly2, fnt_pre_asymmetric_table_extended, fnt_asymmetric_const);

    fnt_base_mul_mont(polyout, poly1, poly2, poly2_asymmetric, fnt_asymmetric_const);
}

void invfnt(int16x8_t r[SMAUGT_N_VEC]) {
    invfnt_bot_opt(r, inv_twist_table+512, 0);
    invfnt_bot_opt(r+16, inv_twist_table+512, 0);

    invfnt_top_opt(r, inv_twist_table);
    invfnt_top_opt(r+8, inv_twist_table+64);
}

